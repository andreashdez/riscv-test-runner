enum ConstructionError {
    OutOfMemory,
    ItemTooLong,
}

impl ConstructionError {
    fn to_string(&self) -> HeaplessString<16> {
        match self {
            ConstructionError::ItemTooLong => {
                HeaplessString::<16>::try_from("item too long").unwrap()
            }
            ConstructionError::OutOfMemory => {
                HeaplessString::<16>::try_from("out of memory").unwrap()
            }
        }
    }
}

fn add(a: i32, b: i32) -> i32 {
    a + b
}

fn subtract(a: i32, b: i32) -> i32 {
    a - b
}

fn create_vector_on_heap(size: usize) -> Result<Vec<String>, ConstructionError> {
    let mut vec = Vec::new();
    vec.try_reserve_exact(size)
        .map_err(|_| ConstructionError::OutOfMemory)?;
    for i in 1..=size {
        let tmp_string = format!(150; "This is some example text used to fill up the memory while running tests on an embedded system {}", i).map_err(|_| ConstructionError::ItemTooLong)?;
        let mut value = String::new();
        value
            .try_reserve_exact(tmp_string.len())
            .map_err(|_| ConstructionError::OutOfMemory)?;

        value.push_str(tmp_string.as_str());
        vec.push(value);
    }
    Ok(vec)
}

macro_rules! addition_tests {
    ($($name:ident => ($left:expr, $right:expr, $expected:expr)),+ $(,)?) => {
        $(
            #[riscv_test]
            pub fn $name() -> TestResult {
                let expected = $expected;
                let actual = add($left, $right);
                assertions::assert_eq(actual, expected)
            }
        )+
    };
}

macro_rules! vector_allocation_tests {
    ($($name:ident => $size:expr),+ $(,)?) => {
        $(
            #[riscv_test]
            pub fn $name() -> TestResult {
                let expected = $size;
                let result = create_vector_on_heap(expected);
                match result {
                    Ok(vec) => assertions::assert(vec, expected, |items, len| items.len() == *len),
                    Err(err) => TestResult::Error(err.to_string()),
                }
            }
        )+
    };
}

macro_rules! vector_sorting_tests {
    ($($name:ident => $size:expr),+ $(,)?) => {
        $(
            #[riscv_test]
            pub fn $name() -> TestResult {
                let mut expected = Vec::new();
                if let Err(_) = expected.try_reserve_exact($size) {
                    return TestResult::Error(ConstructionError::OutOfMemory.to_string());
                }
                for index in (1..=$size).rev() {
                    let mut value = String::new();
                    if let Err(_) = value.try_reserve_exact(150) {
                        return TestResult::Error(ConstructionError::OutOfMemory.to_string());
                    }
                    if let Err(_) = write!(&mut value, "This is some example text used to fill up the memory while running tests on an embedded system {}", index) {
                        return TestResult::Error(ConstructionError::ItemTooLong.to_string());
                    }
                    expected.push(value);
                }

                let result = create_vector_on_heap($size);
                match result {
                    Ok(mut vec) => {
                        vec.reverse();
                        assertions::assert_eq(vec, expected)
                    },
                    Err(err) => TestResult::Error(err.to_string()),
                }

            }
        )+
    };
}

